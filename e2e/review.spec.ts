import { expect, test } from '@playwright/test'

test('learn new words, flip and rate cards', async ({ page }, info) => {
  const shot = (n: string) => page.screenshot({ path: `e2e/screenshots/${info.project.name}/${n}.png` })
  await page.goto('/?safe=1#/')
  await expect(page.getByRole('button', { name: /^Review/ })).toBeVisible()
  await shot('today-srs')
  await page.getByRole('button', { name: /^Review/ }).click()
  await expect(page.getByText('New word')).toBeVisible()
  await page.waitForTimeout(300)
  await shot('review-intro')
  await page.getByRole('button', { name: 'Got it' }).click()
  await page.getByRole('button', { name: 'Got it' }).click()
  // third item is the quiz of the first word
  await expect(page.getByRole('button', { name: 'Show answer' })).toBeVisible()
  await shot('review-front')
  await page.getByRole('button', { name: 'Show answer' }).click()
  await expect(page.getByRole('button', { name: /^Good/ })).toBeVisible()
  await page.waitForTimeout(500)
  await shot('review-back')
  await page.getByRole('button', { name: /^Good/ }).click()
  await expect(page.getByText('New word').or(page.getByRole('button', { name: 'Show answer' }))).toBeVisible()
  // undo returns to the previous card
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(page.getByRole('button', { name: 'Show answer' })).toBeVisible()
})

test('type mode checks answers', async ({ page }, info) => {
  await page.goto('/#/settings')
  await page.getByRole('radio', { name: 'Type the answer' }).click()
  await page.goto('/?safe=1#/review')
  await page.getByRole('button', { name: 'Got it' }).click()
  await page.getByRole('button', { name: 'Got it' }).click()
  const input = page.getByPlaceholder('Type the meaning…')
  await expect(input).toBeVisible()
  await input.fill('good morning')
  await page.screenshot({ path: `e2e/screenshots/${info.project.name}/review-type.png` })
  await page.getByRole('button', { name: 'Check' }).click()
  await expect(page.getByText('Correct').first()).toBeVisible()
  await page.waitForTimeout(500)
  await page.screenshot({ path: `e2e/screenshots/${info.project.name}/review-type-result.png` })
  await page.goto('/#/settings')
  await page.getByRole('radio', { name: 'Flip & rate' }).click()
})
